//! gen_decl_docs.zig: the declaration's descriptions, harvested out of
//! src/decl.zig at build time, as capsper's build/gen_config_docs.zig
//! harvests its settings' (STANDALONE.md, "Decided": one source for every
//! description).
//!
//!   gen-decl-docs DECL.zig OUT.zig
//!
//! Each field's description is the doc comment beside it, and stays there,
//! next to the type and default it describes. `@typeInfo` gives a field's
//! name and type and nothing of its doc comment, so this reads the source,
//! with `std.zig.Ast`, the compiler's own parser: a doc comment is found by
//! its place in the token stream, not guessed at with a pattern. It runs at
//! build time because parsing needs an allocator, which comptime has not.
//!
//! The output is a flat list of container name, field name and text, with
//! no attempt to resolve which type a field holds, which would mean
//! reimplementing name resolution: src/decl_docs.zig walks the real types
//! with `@typeInfo`, where the answer is known, and looks each field up here
//! by name. A field in a container that is not a top-level
//! `const X = struct` (or `enum`) is not listed, as it has no name to look
//! up by.
//!
//! A description keeps its lines, where capsper's joins them: it is
//! Markdown the NixOS manual renders, whose paragraphs and lists are made
//! of line breaks. Each line loses its `///` and the one space after it,
//! and nothing else, so a list item's continuation keeps its indent.
//!
//! Built for the host, never shipped, so std.fs and std.debug.print are
//! this file's to use: fdlint's rules are for src/.

const std = @import("std");

pub fn main() !void {
    var arena_state = std.heap.ArenaAllocator.init(std.heap.page_allocator);
    defer arena_state.deinit();
    const arena = arena_state.allocator();

    const args = try std.process.argsAlloc(arena);
    if (args.len != 3) {
        std.debug.print("usage: gen-decl-docs DECL.zig OUT.zig\n", .{});
        std.process.exit(1);
    }

    const source = try std.fs.cwd().readFileAllocOptions(arena, args[1], 4 << 20, null, .of(u8), 0);
    var ast = try std.zig.Ast.parse(arena, source, .zig);
    if (ast.errors.len > 0) {
        std.debug.print("{s}: does not parse\n", .{args[1]});
        std.process.exit(1);
    }

    var out: std.Io.Writer.Allocating = .init(arena);
    try out.writer.writeAll(
        \\//! Generated by build/gen_decl_docs.zig. Do not edit.
        \\//!
        \\//! The doc comment beside each field of the declaration, made readable
        \\//! by the program. See src/decl_docs.zig.
        \\
        \\pub const Field = struct {
        \\    /// The container the field is declared in, as written: "Limits".
        \\    container: []const u8,
        \\    name: []const u8,
        \\    /// The doc comment, each line without its `///` and the space
        \\    /// after it, the lines joined by newlines. Empty when the field has
        \\    /// none.
        \\    doc: []const u8,
        \\};
        \\
        \\pub const fields = [_]Field{
        \\
    );

    var count: usize = 0;
    for (0..ast.nodes.len) |i| {
        const node: std.zig.Ast.Node.Index = @enumFromInt(i);
        const field = ast.fullContainerField(node) orelse continue;
        const container = containerOf(ast, node) orelse continue;
        const doc = try docComment(arena, ast, field.firstToken());
        try out.writer.print("    .{{ .container = \"{f}\", .name = \"{f}\", .doc = \"{f}\" }},\n", .{
            std.zig.fmtString(container),
            std.zig.fmtString(ast.tokenSlice(field.ast.main_token)),
            std.zig.fmtString(doc),
        });
        count += 1;
    }
    try out.writer.writeAll("};\n");

    if (count == 0) {
        std.debug.print("{s}: found no fields, which cannot be right\n", .{args[1]});
        std.process.exit(1);
    }
    try std.fs.cwd().writeFile(.{ .sub_path = args[2], .data = out.written() });
}

/// The name of the `const X = struct { ... }` a field is declared in:
/// back through the tokens before the field to the `{` that opens its
/// container, skipping balanced braces of the fields before it, then back
/// to the `struct` or `enum` keyword and the identifier two tokens before
/// that. Null for any other shape, a `union(enum)` included.
fn containerOf(ast: std.zig.Ast, node: std.zig.Ast.Node.Index) ?[]const u8 {
    const tags = ast.tokens.items(.tag);
    var tok = ast.firstToken(node);
    var depth: usize = 0;
    while (tok > 0) {
        tok -= 1;
        switch (tags[tok]) {
            .r_brace => depth += 1,
            .l_brace => {
                if (depth == 0) break;
                depth -= 1;
            },
            else => {},
        }
    } else return null;

    var kw = tok;
    const floor = if (tok > 8) tok - 8 else 0;
    while (kw > floor) {
        kw -= 1;
        if (tags[kw] == .keyword_struct or tags[kw] == .keyword_enum or tags[kw] == .keyword_union) break;
    } else return null;

    if (kw < 2 or tags[kw - 1] != .equal or tags[kw - 2] != .identifier) return null;
    return ast.tokenSlice(kw - 2);
}

/// The doc comment immediately above `token`, its lines kept.
fn docComment(arena: std.mem.Allocator, ast: std.zig.Ast, token: u32) ![]const u8 {
    const tags = ast.tokens.items(.tag);
    var first = token;
    while (first > 0 and tags[first - 1] == .doc_comment) first -= 1;

    var text: std.Io.Writer.Allocating = .init(arena);
    var tok = first;
    while (tok < token) : (tok += 1) {
        const raw = ast.tokenSlice(tok)[3..];
        const line = if (std.mem.startsWith(u8, raw, " ")) raw[1..] else raw;
        if (tok > first) try text.writer.writeByte('\n');
        try text.writer.writeAll(std.mem.trimRight(u8, line, " \t\r"));
    }
    return text.written();
}
